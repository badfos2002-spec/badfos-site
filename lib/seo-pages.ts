import type { DesignAreaType, ProductType } from './types'
import { CAP_MIN_QUANTITY, BUFF_QUANTITIES } from './constants'

// Prices in the copy are {{tokens}} (lib/seo-price-tokens.ts), resolved live on
// the client from the admin pricing — never shekel amounts baked in at build.
// CAP_MIN_QUANTITY / BUFF_QUANTITIES are code-only constants (not admin-editable),
// so they stay as plain interpolation.

/** Hebrew-named files under /public/assets must be URL-encoded for next/image
 *  (the optimizer's internal fetch fails on raw unicode + spaces). */
const asset = (filename: string) => '/assets/' + encodeURIComponent(filename)

export interface SeoPageBenefit {
  title: string
  text: string
}

export interface SeoPageParagraph {
  title: string
  text: string
}

export interface SeoPageFaq {
  q: string
  /** Number-free answer — also the FAQ JSON-LD text, so no prices and no {{tokens}} */
  a: string
  /** Optional live-priced sentence(s) shown after `a` on the page only (may hold {{tokens}}) */
  aLive?: string
}

/**
 * Light per-page visual accent. Brand yellow stays the primary color (CTA buttons
 * are unchanged) — these are secondary flavor classes only.
 * IMPORTANT: values must be full static Tailwind class strings (this file is in
 * tailwind.config content paths, so the JIT extractor picks the tokens up as-is).
 */
export interface SeoPageAccent {
  /** Classes for chips/highlights: soft bg + text color + border color */
  badge: string
  /** Gradient stops for benefit icon backgrounds (from-… to-…) */
  gradient: string
  /** Topic emoji shown in the hero badge and ideas section title */
  emoji: string
}

/** Playful print-slogan / use-case ideas rendered as chips (long-tail SEO) */
export interface SeoPageIdeas {
  title: string
  items: string[]
}

/** One "איך זה עובד" step (DefaultLayout). Titles must be unique within the page. */
export interface SeoPageStep {
  title: string
  text: string
}

/**
 * A price scenario — NOT a price. DefaultLayout prices it live on the client from
 * the same getters the designers/cart use (admin /admin/pricing overrides
 * included), so no shekel amount is ever frozen into the static page.
 *   unit  = getBasePrice(productType, fabric) + Σ area prices + getSizeSurcharge(size)
 *   total = unit × quantity − live quantity discount (when quantity ≥ its minimum)
 */
export interface SeoPagePriceExample {
  /** Scenario name shown on the card, e.g. 'חולצת כותנה עם לוגו בחזה' (unique per page) */
  label: string
  productType: ProductType
  /** Sub-type passed to getBasePrice — REQUIRED for tshirt (cotton/dri-fit/polo/oversized),
   *  sweatshirt (kangaroo/putter/zip), cap (tembel/mesh), tote (volume/drawstring) */
  fabric?: string
  /** Print area ids that exist for this productType in lib/constants (*_DESIGN_AREAS) */
  areas: DesignAreaType[]
  /** Units in the scenario (default 1). Caps ≥ CAP_MIN_QUANTITY, buffs = a BUFF_QUANTITIES pack (build-checked). */
  quantity?: number
  /** Size id with a surcharge, e.g. '3XL' (default: standard size, no surcharge) */
  size?: string
  /** Optional short line under the price */
  note?: string
}

export interface SeoPage {
  slug: string
  /** Product landing pages: the designer this page promotes — CTAs link to /designer/<type> */
  productType?: ProductType
  metaTitle: string
  metaDescription: string
  h1: string
  heroText: string
  /** Punchy one-liner rendered as an accent-colored badge chip under the H1 */
  audienceLine?: string
  /** Per-page visual accent (optional — pages without it keep the default look) */
  accent?: SeoPageAccent
  /** "רעיונות לכיתובים" chips section, rendered between gallery and body copy */
  ideas?: SeoPageIdeas
  benefits: SeoPageBenefit[]
  paragraphs: SeoPageParagraph[]
  faq: SeoPageFaq[]
  galleryImages: string[]
  /** Optional per-image alt texts (index-aligned with galleryImages). Use for stock
   *  photos, which must not be captioned as customer work. */
  galleryAlts?: string[]
  /** Optional small caption under the gallery (e.g. 'תמונות להמחשה' for stock photos) */
  galleryNote?: string
  /** 1200x630 real-photo crop for WhatsApp/social shares (og:image), served from /public/og */
  ogImage: string
  ctaText: string
  /** Sibling SEO pages for cross-linking ("אולי יעניין אתכם גם") */
  related: string[]
  /** Prefilled WhatsApp message for this page's CTAs (fallback: generic "מתעניין ב<h1>") */
  waMessage?: string
  /** "איך זה עובד" steps (DefaultLayout only; 3 recommended — the timeline is 3 columns on desktop) */
  steps?: SeoPageStep[]
  /** Live-priced scenarios (DefaultLayout only) */
  priceExamples?: SeoPagePriceExample[]
  /** "לפני שמזמינים" checklist items (DefaultLayout only; items must be unique) */
  checklist?: string[]
}

