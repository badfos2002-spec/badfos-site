// ---------------------------------------------------------------------------
// Live prices for the product landing pages — quoted via the pricing getters
// so the copy (and the FAQ JSON-LD derived from it) always matches
// lib/constants and never rots. Evaluated at module load (code defaults).
// ---------------------------------------------------------------------------
const areaPrice = (productType: ProductType, areaId: string): number =>
  getDesignAreasByProductType(productType).find((a) => a.id === areaId)?.price ?? 0

/** Cheapest printed unit: base price + the least expensive print area */
const printedFrom = (productType: ProductType): number =>
  getBasePrice(productType) + Math.min(...getDesignAreasByProductType(productType).map((a) => a.price))

const DELIVERY_COST = getLiveShippingCost('delivery')
const QTY_DISCOUNT = getLiveQuantityDiscount()

/** Hebrew-named files under /public/assets must be URL-encoded for next/image
 *  (the optimizer's internal fetch fails on raw unicode + spaces). */
